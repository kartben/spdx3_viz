/**
 * Generates src/spdx/hierarchy.js from the official SPDX model: reads the
 * published JSON-LD ontology (spdx-model.jsonld) for each spec version and
 * writes a compact { class: superclass } map keyed by the JSON-LD compact names
 * SBOMs use. Run `node scripts/gen-spdx-model.mjs`; needs network, and the
 * committed output means the app never does.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

// Frozen 3.0.1 plus the in-progress 3.1-dev line (ahead of any rc tag, so newer
// classes like functionalsafety_Assumption are included). Reading both catches
// any conflict if 3.1 ever stops being a superset.
const VERSIONS = ['3.0.1', '3.1-dev'];
const url = (v) =>
  `https://raw.githubusercontent.com/spdx/spdx-spec/gh-pages/v${v}/rdf/spdx-model.jsonld`;

const OWL_CLASS = 'http://www.w3.org/2002/07/owl#Class';
const RDFS_SUBCLASS = 'http://www.w3.org/2000/01/rdf-schema#subClassOf';

// IRI `https://spdx.org/rdf/3/terms/<Profile>/<Class>` -> compact name.
function compact(iri) {
  const m = (iri || '').match(/\/terms\/([^/]+)\/([^/]+)$/);
  if (!m) return null;
  const [, profile, cls] = m;
  return profile === 'Core' ? cls : `${profile.toLowerCase()}_${cls}`;
}

function hierarchyFrom(graph) {
  const parent = {};
  for (const node of graph) {
    const types = [].concat(node['@type'] || []);
    if (!types.includes(OWL_CLASS)) continue;
    const name = compact(node['@id']);
    if (!name) continue;
    const sub = node[RDFS_SUBCLASS]?.[0]?.['@id'];
    parent[name] = compact(sub) || null; // null = a hierarchy root (e.g. Element)
  }
  return parent;
}

const merged = {};
for (const v of VERSIONS) {
  const res = await fetch(url(v));
  if (!res.ok) throw new Error(`fetch ${url(v)} -> HTTP ${res.status}`);
  const graph = await res.json();
  const h = hierarchyFrom(graph);
  for (const [cls, sup] of Object.entries(h)) {
    if (cls in merged && merged[cls] !== sup) {
      throw new Error(`subclass conflict for ${cls}: ${merged[cls]} vs ${sup} (v${v})`);
    }
    merged[cls] = sup;
  }
  console.error(`v${v}: ${Object.keys(h).length} classes`);
}

const entries = Object.keys(merged)
  .sort()
  .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(merged[k])}`)
  .join(',\n');

const banner =
  `// AUTO-GENERATED by scripts/gen-spdx-model.mjs from the official SPDX model\n` +
  `// (${VERSIONS.map((v) => `v${v}`).join(' + ')}). Do not edit by hand.\n`;

const body =
  `${banner}\n` +
  `/** Every SPDX class mapped to its immediate superclass (null = a root). */\n` +
  `export const CLASS_PARENT = Object.freeze({\n${entries}\n});\n\n` +
  `/**\n` +
  ` * Every SPDX class name as a string-literal union, so isA()/bucketOf() reject\n` +
  ` * an unknown class at type-check time.\n` +
  ` *\n` +
  ` * @typedef {keyof typeof CLASS_PARENT} SpdxClass\n` +
  ` */\n`;

const outPath = resolve(dirname(fileURLToPath(import.meta.url)), '../src/spdx/hierarchy.js');
writeFileSync(outPath, body);
console.error(`wrote ${outPath} (${Object.keys(merged).length} classes)`);

/**
 * Generates src/changelog.js from CHANGELOG.md at the repo root: CHANGELOG.md
 * is the single source of truth (edited by hand, also what GitHub renders),
 * and this script turns it into the plain data the "What's new" modal reads.
 * Run `node scripts/gen-changelog.mjs` after editing CHANGELOG.md.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const here = dirname(fileURLToPath(import.meta.url));
const changelogPath = resolve(here, '../CHANGELOG.md');
const outPath = resolve(here, '../src/changelog.js');

const HEADING_RE = /^##\s+(.+)$/;
const VERSION_RE = /^\[([^\]]+)\]\s*-\s*(\d{4}-\d{2}-\d{2})$/;
const ITEM_RE = /^-\s+(?:\*\*([^*:]+):?\*\*\s*)?(.+)$/;

function parseChangelog(markdown) {
  const releases = [];
  let current = null;
  for (const line of markdown.split('\n')) {
    const heading = line.match(HEADING_RE);
    if (heading) {
      const versioned = heading[1].match(VERSION_RE);
      current = versioned
        ? { version: versioned[1], date: versioned[2], items: [] }
        : { version: heading[1].trim(), date: null, items: [] };
      releases.push(current);
      continue;
    }
    const item = current && line.match(ITEM_RE);
    if (item) current.items.push({ tag: item[1] || '', text: item[2] });
  }
  return releases;
}

// Drop sections with no items (e.g. a freshly reopened "## Unreleased" between
// releases) so the "What's new" modal never shows an empty heading.
const releases = parseChangelog(readFileSync(changelogPath, 'utf8')).filter(
  (release) => release.items.length > 0
);
if (!releases.length) throw new Error(`No releases parsed from ${changelogPath}`);

const out = `/**
 * GENERATED by scripts/gen-changelog.mjs from CHANGELOG.md. Do not edit by
 * hand — edit CHANGELOG.md and re-run the script.
 *
 * @module changelog
 */
export const CHANGELOG = ${JSON.stringify(releases, null, 2)};
`;

const prettierConfig = await resolveConfig(outPath);
const formatted = await format(out, { ...prettierConfig, parser: 'babel' });
writeFileSync(outPath, formatted);
console.log(`Wrote ${releases.length} releases to ${outPath}`);

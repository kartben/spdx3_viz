/**
 * Generates src/lib/icon-paths.js from Google's Material icons: reads the chosen
 * `filled` glyphs and writes a compact { iconKey: pathData } map, all normalized
 * to a 24x24 viewBox. Run `node scripts/gen-node-icons.mjs`; the committed output
 * means the app never imports an icon package at runtime (they stay dev deps).
 *
 * Two sources, since the classic set lacks a few newer glyphs:
 *   - a plain string     -> Material Design Icons `filled/<name>.svg` (24x24)
 *   - { symbol: 'name' } -> Material Symbols `outlined/<name>-fill.svg`, whose
 *                           native 0 -960 960 960 viewBox is transformed to 24x24
 *
 * To add or change a glyph, edit ICONS below and re-run. The mapping of SPDX
 * elements / views onto these keys lives in src/lib/icons.js.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';
import svgpath from 'svgpath';

// Semantic icon key -> Material icon source. Keys match the vocabulary resolved
// by src/lib/icons.js.
const ICONS = {
  // Generic artifact-type defaults (used when no software_primaryPurpose applies).
  package: { symbol: 'package' },
  file: 'description',
  folder: 'folder',
  // software_primaryPurpose glyphs — a purpose is a property of the shared
  // SoftwareArtifact base, so these apply to both Files and Packages alike
  // (see PURPOSE_ICON in src/lib/icons.js).
  application: 'apps',
  container: 'widgets',
  operating_system: 'desktop_windows',
  library: { symbol: 'deployed_code' },
  module: 'extension',
  source: 'code',
  executable: 'terminal',
  archive: 'folder_zip',
  documentation: 'article',
  image: 'album',
  data: 'table_chart',
  install: 'install_desktop',
  patch: 'healing',
  test: 'science',
  // Other node types.
  ai: 'psychology',
  dataset: 'dataset',
  config: 'settings',
  tool: 'construction',
  build: 'build',
  agent_person: 'person',
  agent_org: 'business',
  agent_bot: 'smart_toy',
  license: 'balance',
  external: 'open_in_new',
  vulnerability: 'bug_report',
  hardware: 'memory',
  requirement: 'assignment',
  requirement_verification: 'fact_check',
  assumption: 'help',
  evaluation: 'assessment',
  // Sidebar view glyphs that don't map onto an SPDX element type.
  view_dashboard: 'dashboard',
  view_graph: 'hub',
  view_security: 'security',
  view_raw: 'data_object',
  view_statistics: { symbol: 'monitoring' },
  // Graph toolbar toggle glyphs (not tied to an SPDX element type).
  toggle_icons: 'image',
  toggle_aggregate: 'workspaces',
  toggle_hide_orphans: 'visibility_off'
};

const here = dirname(fileURLToPath(import.meta.url));
const classicDir = resolve(here, '../node_modules/@material-design-icons/svg/filled');
const symbolsDir = resolve(here, '../node_modules/@material-symbols/svg-400/outlined');

/**
 * Joins every `<path d="…">` in a Material icon SVG into one path string. Some
 * glyphs (e.g. psychology, menu_book) are drawn with several subpaths, and each
 * `d` starts with a move command so they concatenate cleanly for one fill.
 */
function pathOf(svg, name) {
  const ds = [...svg.matchAll(/\bd="([^"]+)"/g)].map((m) => m[1]);
  if (!ds.length) throw new Error(`No <path d> found in ${name}.svg`);
  return ds.join(' ');
}

/** Resolves an ICONS entry to a 24x24 path `d`, transforming Symbols glyphs. */
function pathFor(spec) {
  if (typeof spec === 'string') {
    return pathOf(readFileSync(resolve(classicDir, `${spec}.svg`), 'utf8'), spec);
  }
  const d = pathOf(
    readFileSync(resolve(symbolsDir, `${spec.symbol}-fill.svg`), 'utf8'),
    spec.symbol
  );
  // Material Symbols live in a 0 -960 960 960 box; shift up by 960 then scale to 24.
  return svgpath(d)
    .translate(0, 960)
    .scale(24 / 960)
    .round(3)
    .toString();
}

const entries = Object.entries(ICONS).map(([key, spec]) => `  ${key}: '${pathFor(spec)}'`);

const out = `/**
 * GENERATED by scripts/gen-node-icons.mjs from Google's Material icons (Material
 * Design Icons \`filled\` + a few Material Symbols). Do not edit by hand — re-run
 * the script to change the glyph set. Each value is a single \`d\` string
 * normalized to a 24x24 viewBox.
 *
 * @module lib/icon-paths
 */
export const ICON_PATHS = {
${entries.join(',\n')}
};
`;

const outPath = resolve(here, '../src/lib/icon-paths.js');
// Run through Prettier (with the repo config) so the committed output always
// matches `npm run format:check`.
const prettierConfig = await resolveConfig(outPath);
const formatted = await format(out, { ...prettierConfig, parser: 'babel' });
writeFileSync(outPath, formatted);
console.log(`Wrote ${entries.length} icons to ${outPath}`);
